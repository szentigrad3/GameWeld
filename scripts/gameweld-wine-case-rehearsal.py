#!/usr/bin/env python3
"""Synthetic Wine case-lookup rehearsal, NEVER an importer or game-prefix test.

Default is a read-only preview. Explicit --run-disposable-wine creates a fresh
private temporary Wine prefix and four TINY synthetic files only. All source
material is generated by this script; nothing comes from the rejected ZIP.
A Wine prefix is NOT an OS sandbox. Never execute untrusted archives here.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import sys
import tempfile

TOKENS = {
    "upper_file": b"GW_CASE_UPPER_FILE_7F2C",
    "lower_file": b"GW_CASE_LOWER_FILE_7F2C",
    "upper_dir": b"GW_CASE_UPPER_DIR_7F2C",
    "lower_dir": b"GW_CASE_LOWER_DIR_7F2C",
}
WIN_TESTS = (
    ("Exact upper-case file", r"C:\GWCaseProbe\InstallUtil.exe", "upper_file"),
    ("Exact lower-case file", r"C:\GWCaseProbe\installutil.exe", "lower_file"),
    ("Ambiguous mixed-case file", r"C:\GWCaseProbe\INSTALLUTIL.EXE", None),
    ("Exact upper-case directory", r"C:\GWCaseProbe\CONFIG\machine.config", "upper_dir"),
    ("Exact mixed-case directory", r"C:\GWCaseProbe\Config\machine.config", "lower_dir"),
    ("Ambiguous lower-case directory", r"C:\GWCaseProbe\config\machine.config", None),
)
TIMEOUT_SECONDS = 100


class WineCaseRefused(ValueError):
    pass


def safe_root(root: Path) -> None:
    if (not root.is_absolute() or root.name != "prepared-wemod" or
            root.parent.name != "gameweld" or
            any(c.casefold() in {"steamapps", "compatdata", "pfx"} for c in root.parts) or
            any(p.is_symlink() for p in (root, *root.parents)) or
            not root.is_dir() or
            stat.S_IMODE(root.stat().st_mode) & 0o077):
        raise WineCaseRefused("Private GameWeld prepared-wemod cache unavailable or unsafe")


def synthetic_files(prefix: Path, *, reverse_creation_order: bool = False) -> None:
    drive = prefix / "drive_c"
    if drive.is_symlink() or not drive.is_dir():
        raise WineCaseRefused("Wine did not create a safe private C: drive")
    root = drive / "GWCaseProbe"
    if root.exists() or root.is_symlink():
        raise WineCaseRefused("Synthetic Wine test directory unexpectedly exists")
    root.mkdir(mode=0o700)
    files = {
        root / "InstallUtil.exe": TOKENS["upper_file"],
        root / "installutil.exe": TOKENS["lower_file"],
        root / "CONFIG" / "machine.config": TOKENS["upper_dir"],
        root / "Config" / "machine.config": TOKENS["lower_dir"],
    }
    folders = (root / "CONFIG", root / "Config")
    for folder in (reversed(folders) if reverse_creation_order else folders):
        folder.mkdir(mode=0o700)
    entries = list(files.items())
    for destination, token in (reversed(entries) if reverse_creation_order else entries):
        fd = os.open(destination,
                     os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                     getattr(os, "O_NOFOLLOW", 0), 0o600)
        with os.fdopen(fd, "wb") as stream:
            stream.write(token + b"\r\n")
    if (len({p.stat().st_ino for p in files}) != len(files) or
            any(p.read_bytes() != token + b"\r\n"
                for p, token in files.items())):
        raise WineCaseRefused("Host filesystem did not preserve distinct case variants")


def result_token(output: bytes) -> str:
    found = [name for name, token in TOKENS.items() if token in output]
    return found[0] if len(found) == 1 else "UNRESOLVED"


def environment_for_test(folder: Path) -> dict[str, str]:
    env = os.environ.copy()
    # Do not reuse inherited active Steam, Proton or Wine runtime hints.
    for key in tuple(env):
        if (key.startswith(("WINE", "STEAM_COMPAT_", "PROTON_", "PRESSURE_VESSEL_")) or
                key in {"LD_PRELOAD", "WINESERVER", "WINELOADER", "WINEDLLPATH"}):
            env.pop(key, None)
    prefix = folder / "wineprefix"
    home = folder / "home"
    home.mkdir(mode=0o700)
    for name in ("cache", "config", "data"):
        (folder / name).mkdir(mode=0o700)
    env.update({
        "HOME": str(home),
        "XDG_CACHE_HOME": str(folder / "cache"),
        "XDG_CONFIG_HOME": str(folder / "config"),
        "XDG_DATA_HOME": str(folder / "data"),
        "WINEPREFIX": str(prefix),
        "WINEARCH": "win64",
        "WINEDEBUG": "-all",
        # Do not launch GUI prompts for optional Wine Gecko/Mono setup.
        "WINEDLLOVERRIDES": "mscoree,mshtml=",
    })
    return env


def execute(command: list[str], *, env: dict[str, str], runner=subprocess.run,
            unresolved_on_failure: bool = False):
    try:
        result = runner(
            command, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            timeout=TIMEOUT_SECONDS, check=False, start_new_session=True)
    except subprocess.TimeoutExpired as exc:
        raise WineCaseRefused("Disposable Wine lookup exceeded the bounded timeout") from exc
    if result.returncode != 0:
        if unresolved_on_failure:
            # Missing/ambiguous paths are a valid negative Wine experiment.
            # Do not turn a single failed lookup into a false global PASS.
            return b""
        # Deliberately exclude potentially private paths and raw Wine logs.
        raise WineCaseRefused("Disposable Wine initialization failed (exit status " +
                              str(result.returncode) + ")")
    if len(result.stdout) > 4096 or len(result.stderr) > 8192:
        raise WineCaseRefused("Unexpectedly large Wine diagnostic output")
    return result.stdout


def run_rehearsal(root: Path, *, runner=subprocess.run,
                  wine_exe: str | None = None,
                  cleanup_runner=subprocess.run,
                  reverse_creation_order: bool = False) -> str:
    safe_root(root)
    executable = wine_exe or shutil.which("wine")
    if not executable:
        raise WineCaseRefused("System Wine not found in PATH. No Proton or game prefix tried.")
    results: list[str] = []
    with tempfile.TemporaryDirectory(prefix=".synthetic-wine-case-", dir=root) as temporary:
        folder = Path(temporary)
        env = environment_for_test(folder)
        prefix = Path(env["WINEPREFIX"])
        try:
            # Only Wine's own cmd.exe is launched. The rejected ZIP is never opened.
            execute([executable, "cmd", "/c", "ver"], env=env, runner=runner)
            synthetic_files(prefix, reverse_creation_order=reverse_creation_order)
            for label, path, expected in WIN_TESTS:
                output = execute(
                    [executable, "cmd", "/c", "type", path],
                    env=env, runner=runner, unresolved_on_failure=True)
                observed = result_token(output)
                if observed == "UNRESOLVED":
                    interpretation = "UNRESOLVED"
                elif expected is None:
                    interpretation = "ONE VARIANT RETURNED (ambiguous path)"
                elif observed == expected:
                    interpretation = "MATCHED EXPECTED CASE"
                else:
                    interpretation = "RESOLVED DIFFERENT VARIANT"
                results.append(f"{label}: {observed} — {interpretation}")
        finally:
            # Kill only this disposable WINEPREFIX server, not global Wine.
            server = shutil.which("wineserver")
            if server and runner is subprocess.run:
                try:
                    cleanup_runner(
                        [server, "-k"], env=env, stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL, timeout=15,
                        check=False, start_new_session=True)
                except (OSError, subprocess.TimeoutExpired):
                    pass
    return "\n".join([
        "GAMEWELD — SYNTHETIC WINE CASE LOOKUP (DISPOSABLE)",
        "Source: new isolated Wine prefix; ONLY tiny generated test files",
        "Synthetic creation order: " + (
            "REVERSED" if reverse_creation_order else "NORMAL"),
        *results,
        "Disposable test prefix and synthetic contents: CLEANED UP",
        "Interpretation: host Wine cmd.exe file lookup only — NOT Proton or .NET validation",
        "Rejected archive, game prefixes, Steam and launch options: UNCHANGED",
        "Wine prefixes are not security sandboxes; no untrusted Windows code was run.",
        "Archive staging and installation: STILL BLOCKED",
    ])


def run_creation_order_matrix(root: Path, *, runner=subprocess.run,
                              wine_exe: str | None = None,
                              cleanup_runner=subprocess.run) -> str:
    """Compare observed Wine file lookups across two fresh disposable prefixes."""
    reports = [
        run_rehearsal(root, runner=runner, wine_exe=wine_exe,
                      cleanup_runner=cleanup_runner, reverse_creation_order=False),
        run_rehearsal(root, runner=runner, wine_exe=wine_exe,
                      cleanup_runner=cleanup_runner, reverse_creation_order=True),
    ]
    def outputs(report: str) -> dict[str, str]:
        observations = {}
        for line in report.splitlines():
            if ": " in line and " — " in line:
                label, content = line.split(": ", 1)
                if label in {t[0] for t in WIN_TESTS}:
                    observations[label] = content.split(" — ", 1)[0]
        return observations
    normal, reversed_order = map(outputs, reports)
    if len(normal) != len(WIN_TESTS) or len(reversed_order) != len(WIN_TESTS):
        raise WineCaseRefused("Synthetic lookup matrix did not complete both configurations")
    changed = [key for key in normal if normal[key] != reversed_order[key]]
    result = [
        "GAMEWELD — WINE CASE CREATION-ORDER MATRIX (DISPOSABLE)",
        "Two independently created and deleted synthetic Wine prefixes.",
    ]
    for label, _, expected in WIN_TESTS:
        first, second = normal[label], reversed_order[label]
        classification = (
            "ORDER-DEPENDENT" if label in changed else
            "EXACT CASE OK IN BOTH" if expected and first == expected else
            "CONSISTENT BUT UNRESOLVED" if first == "UNRESOLVED" else
            "SAME RESULT (NOT PROOF OF SAFETY)"
        )
        result.append(f"{label}: normal={first}; reversed={second}; {classification}")
    result.extend([
        "Order-dependent lookup groups: " + str(len(changed)),
        "No order change does NOT prove Windows/.NET or Proton compatibility.",
        "Only host Wine cmd.exe, synthetic files, and private disposable prefixes tested.",
        "All temporary test prefixes cleaned; real rejected ZIP NEVER extracted or executed.",
        "Game prefixes, Steam/Heroic/Lutris and staged cache: UNCHANGED",
        "Real archive staging and installation: STILL BLOCKED",
    ])
    return "\n".join(result)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    cache = Path(os.environ.get("XDG_CACHE_HOME") or str(Path.home() / ".cache"))
    parser.add_argument("--cache-root", type=Path,
                        default=cache / "gameweld/prepared-wemod")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--run-disposable-wine", action="store_true",
                       help="Opt in to a new temporary Wine prefix and built-in cmd.exe")
    modes.add_argument("--run-order-matrix", action="store_true",
                       help="Compare normal/reversed creation order in TWO disposable prefixes")
    args = parser.parse_args()
    try:
        safe_root(args.cache_root)
        if args.run_order_matrix:
            print(run_creation_order_matrix(args.cache_root))
        elif args.run_disposable_wine:
            print(run_rehearsal(args.cache_root))
        else:
            print("GAMEWELD — SYNTHETIC WINE CASE LOOKUP (PREVIEW)")
            print("No Wine process or ZIP operation started.")
            print("Available system Wine: " +
                  ("YES" if shutil.which("wine") else "NO"))
            print("Explicit tests: --run-disposable-wine or --run-order-matrix")
            print("Test uses only synthetic files in a private disposable prefix.")
            print("No archive staging or compatibility approval.")
    except (WineCaseRefused, OSError) as exc:
        parser.exit(2, f"Wine case lookup: BLOCKED — {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
